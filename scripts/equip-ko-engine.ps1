function Convert-ZhWordMap([string]$text) {
    foreach ($kv in $script:EquipWordMap.GetEnumerator()) {
        $text = $text.Replace($kv.Key, $kv.Value)
    }
    return $text
}

function Convert-EquipNameToKo([string]$zh) {
    if (-not $zh) { return '' }
    if ($script:EquipKoOverrides.ContainsKey($zh)) { return $script:EquipKoOverrides[$zh] }

    $s = $zh
    foreach ($rule in $script:EquipSuffixRules) {
        if ($s -match ($rule.Pattern)) {
            $s = $s -replace $rule.Pattern, $rule.Replace
            break
        }
    }

    $s = Convert-ZhWordMap $s
    $s = ($s -replace '\s+', ' ').Trim()

    if (-not $s -or $s -eq $zh) {
        $zhi = [char]0x4E4B
        $de = [char]0x7684
        return ($zh.Replace($zhi, ' ').Replace($de, ' ')).Trim()
    }
    return $s
}

function Get-EquipKo([string]$zh, [string]$en) {
    $ko = Convert-EquipNameToKo $zh
    if ($ko -and $ko -ne $en) { return $ko }
    if ($ko -and $ko -ne $zh) { return $ko }
    $zhi = [char]0x4E4B
    $de = [char]0x7684
    return ($zh.Replace($zhi, ' ').Replace($de, ' ')).Trim()
}
