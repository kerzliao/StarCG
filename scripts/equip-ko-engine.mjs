function applyWordMap(text) {
  let s = text;
  for (const [zh, ko] of Object.entries(WORD_MAP)) s = s.split(zh).join(ko);
  return s;
}

export function convertEquipNameToKo(zh) {
  if (!zh) return '';
  if (overrides[zh]) return overrides[zh];

  let s = zh;
  for (const [re, rep] of SUFFIX_RULES) {
    if (re.test(s)) {
      s = s.replace(re, rep);
      break;
    }
  }
  s = applyWordMap(s);
  s = s.replace(/\s+/g, ' ').trim();
  if (!s || s === zh) return zh.replace(/之/g, ' ').replace(/的/g, ' ').trim();
  return s;
}

export function getEquipKo(zh, en) {
  const ko = convertEquipNameToKo(zh);
  if (ko && ko !== en) return ko;
  if (ko && ko !== zh) return ko;
  return (zh.replace(/之/g, ' ').replace(/的/g, ' ').trim()) || ko;
}
